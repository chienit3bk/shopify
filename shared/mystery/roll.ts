// Where a mystery box's random number comes from.
//
// Shopify Flow's "Run code" step seeds Math.random identically on every run: three real
// orders all got 0.854925 as their first roll. So each box gets its own roll from the order
// itself, mixed with a secret salt the storefront never sees:
//
//   seed = first 32 bits of SHA-256(salt | order id | order createdAt | line item id | box index)
//   r    = mulberry32(seed)()  → a number in [0, 1)
//
// Deterministic per box (anyone holding the salt can re-check a draw), different for every
// box and order, and unpredictable without the salt. SHA-256 rather than a 32-bit string hash
// (FNV-1a, xmur3): a 32-bit hash's state after the salt prefix is only 2^32 values, small enough
// to brute-force from a few published rolls. Flow Run code has no crypto module, hence plain JS.
// scripts/flow/mystery-draw.js inlines this file; shared/mystery/flow-script.test.ts keeps them in step.

/** A salt shorter than this is treated as missing: the box is not drawn. */
export const MIN_SALT_LENGTH = 32;

export interface BoxRef {
  orderId: string;
  createdAt: string;
  lineId: string;
  /** 0-based: quantity 3 → boxes 0, 1, 2. */
  box: number;
}

/** The string that is hashed. The salt comes first; "|" never appears in a gid or an ISO date. */
export function seedText(salt: string, ref: BoxRef): string {
  return [salt, ref.orderId, ref.createdAt, ref.lineId, ref.box].join('|');
}

/** The random number for one box, in [0, 1). */
export function rollFor(salt: string, ref: BoxRef): number {
  if (!salt || salt.length < MIN_SALT_LENGTH) throw new Error('mystery: salt missing or too short');
  const digest = sha256(seedText(salt, ref));
  return mulberry32(digest[0])();
}

/** Mulberry32: a small 32-bit PRNG. Returns a generator of numbers in [0, 1). */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return function next() {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

